-- QUARTER()

SELECT TRANSACTIONID,TRANSACTIONDATE,QUARTER(TRANSACTIONDATE) AS QUARTER_NUMBER
FROM TRANSACTIONS;

SELECT QUARTER(TRANSACTIONDATE) AS QUARTERS,COUNT(*) AS TRANSACTION_COUNT,
SUM(AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS
WHERE TRANSACTIONDATE IS NOT NULL
GROUP BY QUARTER(TRANSACTIONDATE);

-- DATEDIFF()

SELECT LOANID,STARTDATE,ENDDATE,DATEDIFF(ENDDATE,STARTDATE) AS LOAN_DAYS
FROM LOANS;

-- CALCULATE LOAN DURATION IN TERMS OF YEAR

SELECT LOANID,STARTDATE,ENDDATE,ROUND(DATEDIFF(ENDDATE,STARTDATE)/365,2) AS LOAN_YEARS
FROM LOANS
WHERE ENDDATE IS NOT NULL;

-- TIMESTAMDIFF()

SELECT CUSTOMERID,FIRSTNAME,BIRTHDATE,TIMESTAMPDIFF(YEAR,BIRTHDATE,CURDATE()) AS AGE
FROM CUSTOMERS;

-- AGE GROUP

SELECT CUSTOMERID,FIRSTNAME,BIRTHDATE,TIMESTAMPDIFF(YEAR,BIRTHDATE,CURDATE()) AS AGE,
CASE
WHEN TIMESTAMPDIFF(YEAR,BIRTHDATE,CURDATE()) < 25 THEN "Young Adult"
WHEN TIMESTAMPDIFF(YEAR,BIRTHDATE,CURDATE()) BETWEEN 25 AND 40 THEN "Adult"
ELSE "Senior"
END AS AGE_GROUP
FROM CUSTOMERS;

-- DATE_FORMAT()

SELECT TRANSACTIONDATE,DATE_FORMAT(TRANSACTIONDATE,'%d-%m-%Y') AS FORMATED_DATE
FROM TRANSACTIONS;

SELECT TRANSACTIONDATE,DATE_FORMAT(TRANSACTIONDATE,'%M-%Y') AS MONTH_YEAR
FROM TRANSACTIONS;

-- MONTHLY TRANSACTIONS

SELECT 
DATE_FORMAT(TRANSACTIONDATE,'%Y-%m') AS MONTH,
COUNT(*) AS TRANSACTION_COUNTS,
SUM(AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS
WHERE TRANSACTIONDATE IS NOT NULL
GROUP BY DATE_FORMAT(TRANSACTIONDATE,'%Y-%m')
ORDER BY MONTH;

