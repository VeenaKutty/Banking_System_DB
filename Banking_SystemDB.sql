-- Functions

-- String Functions

-- CONCAT() COMBINES MULTIPLE STRINGS

SELECT CUSTOMERID, concat(FIRSTNAME," ",LASTNAME) AS FULL_NAME
FROM CUSTOMERS;

-- UPPER()

-- IT CONVERTS THE CASES INTO UPPER CASES

SELECT CUSTOMERID, UPPER(concat(FIRSTNAME," ",LASTNAME)) AS FULL_NAME
FROM CUSTOMERS;

-- LOWER()

-- IT CONVERTS THE CASES INTO LOWER CASES

SELECT CUSTOMERID, LOWER(concat(FIRSTNAME," ",LASTNAME)) AS FULL_NAME
FROM CUSTOMERS;

-- LENGTH()
-- FINDS THE NUMBER OF LENGTH

SELECT FIRSTNAME, LENGTH(FIRSTNAME) AS NAMELENGTH
FROM CUSTOMERS
HAVING NAMELENGTH <= 5
ORDER BY NAMELENGTH DESC LIMIT 1 OFFSET 1; -- OFFSET IS USED TO SKIP THE VALUES

-- CHAR_LENGTH()

-- CALCULATES THE NUMBER OF STRINGS

SELECT FIRSTNAME, char_length(FIRSTNAME) AS CHARACTER_LENGTH
FROM CUSTOMERS;

-- LEFT()
-- EXTRACTS THE DATA FROM LEFT SIDE

SELECT FIRSTNAME, LEFT(FIRSTNAME,3) AS FIRST_3_CHAR
FROM CUSTOMERS;

-- RIGHT()

-- EXTRACTS DATA FROM THE RIGHT SIDE

SELECT PHONE, RIGHT(PHONE,4) AS LAST4DIGITS
FROM CUSTOMERS;

-- DISPLAY MASKED ACCOUNT

SELECT CUSTOMERID, CONCAT("XXXXXX",RIGHT(PHONE,4)) AS MASKED_PHONE
FROM CUSTOMERS;

-- SUBSTRING()

-- IT EXTRACTS THE PORTION OF A STRING

SELECT EMAIL, SUBSTRING(EMAIL,1,5) AS EMAIL_PART
FROM CUSTOMERS; 	

-- SUBSTRING_INDEX()

SELECT EMAIL, substring_index(EMAIL,"@",1) AS EMAIL_PART
FROM CUSTOMERS;

-- TRIM()
-- REMOVES USELESS SPACES

SELECT TRIM("Veena Kutty     ") AS NAME;

-- REPLACE()
-- REPLACES THE VALUES

SELECT EMAIL, REPLACE(EMAIL,'gmail.com','email.com') AS EMAILS
FROM CUSTOMERS;

-- LOCATE()
-- FINDS THE POSITION OF THE CHARACTER/STRING

SELECT EMAIL,LOCATE("@",EMAIL) AS POSITION
FROM CUSTOMERS;

-- MATH FUNCTIONS

-- ROUND()
-- ROUNDS OFF THE DECIMAL VALUES

SELECT ACCOUNTID,BALANCE,ROUND(BALANCE,0) AS ROUNDED_BALANCE
FROM ACCOUNTS;

-- CEIL()/CEILING()
-- IT ROUNDS UP THE VALUE

SELECT BALANCE,CEIL(BALANCE) AS ROUNDUP_BALANCE
FROM ACCOUNTS;

-- FLOOR()
-- IT ROUNDS DOWN THE VALUE

SELECT BALANCE,FLOOR(BALANCE) AS ROUNDDOWN_BALANCE
FROM ACCOUNTS;

-- ABS()
-- RETURNS THE ABSOLUTE VALUE

SELECT ABS(-8754) AS ABSOLUTE_VALUE;

-- MOD()
-- RETURNS REMAINING VALUE

SELECT ACCOUNTID,MOD(ACCOUNTID,2) AS REMINDER
FROM ACCOUNTS;

-- CASE THEN END IS JUST LIKE IF - ELSE STATMENT

SELECT ACCOUNTID,MOD(ACCOUNTID,2) AS REMINDER,CASE
WHEN MOD(ACCOUNTID,2)=0 THEN "Even"
ELSE "Odd"
END AS ID_TYPE
FROM ACCOUNTS;

-- POWER()
--  WORKS LIKE INDICES

SELECT POWER(2,4) AS RESULT;

-- SQRT()
-- RETURNS THE SQUARE ROOT OF THE VALUE

SELECT BALANCE,SQRT(BALANCE) AS SQRT_BALANCE
FROM ACCOUNTS;

-- GREATEST()
-- COMPARES VALUES 

SELECT ACCOUNTID, BALANCE,GREATEST(BALANCE,25000) AS MINIMUM_BALANCE
FROM ACCOUNTS;

-- LEAST()
-- COMPARES VALUES

SELECT ACCOUNTID,BALANCE,LEAST(BALANCE,50000) AS MAX_LIMIT
FROM ACCOUNTS;

-- CALCULATE ANNUAL INTEREST

SELECT LOANID,LOANAMOUNT,INTERESTRATE, ROUND(LOANAMOUNT * INTERESTRATE / 100,2) AS ANNUAL_INTEREST
FROM LOANS;

-- LOAN AMOUNT + INTEREST

SELECT LOANID,LOANAMOUNT,INTERESTRATE, 
ROUND(LOANAMOUNT + (LOANAMOUNT * INTERESTRATE / 100),2) AS PRINCIPAL_PLUS_ONEYEAR_INTEREST
FROM LOANS;

-- BALANCE CATEGORY

SELECT ACCOUNTID, BALANCE,
CASE
WHEN BALANCE IS NULL THEN "Unkown"
WHEN BALANCE < 10000 THEN "Low"
WHEN BALANCE < 50000 THEN "Medium"
ELSE "High"
END AS BALANCE_CATEGORY
FROM ACCOUNTS;

